// Turns the legacy content (scripts/content-map.mjs) into supabase/seed.sql with stable ids.
// Run: node scripts/build-seed.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const NAMESPACE = 'deen-roadmap-v2';

/** Deterministic UUID (v5-style, sha1) for a content path such as "L1/learning/mafateeh/3". */
export function stableId(contentPath) {
  const h = createHash('sha1').update(`${NAMESPACE}:${contentPath}`).digest('hex');
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const kindOf = (item) => item.kind ?? (/drive\.google\.com/.test(item.url) ? 'book' : 'video');

export function buildSeed(map) {
  const levels = [];
  const tracks = [];
  const sections = [];
  const items = [];
  const byUrl = new Map();

  const walkSection = (section, trackId, trackPath, parentId, parentPath, sort) => {
    const sectionPath = `${parentPath ?? trackPath}/${section.key}`;
    const id = stableId(sectionPath);
    sections.push(
      `(${q(id)}, ${q(trackId)}, ${q(parentId)}, ${q(section.title)}, ${q(section.description)}, ${q(section.introAudioUrl)}, ${sort})`,
    );
    (section.items ?? []).forEach((item, i) => {
      items.push(
        `(${q(stableId(`${sectionPath}/${i}`))}, ${q(id)}, ${q(kindOf(item))}, ${q(item.shortTitle)}, ${q(item.fullTitle)}, ${q(item.description)}, ${q(item.url)}, ${i})`,
      );
      byUrl.set(item.url, [...(byUrl.get(item.url) ?? []), item.shortTitle]);
    });
    (section.children ?? []).forEach((child, i) => walkSection(child, trackId, trackPath, id, sectionPath, i));
  };

  for (const level of map) {
    const levelPath = `L${level.number}`;
    const levelId = stableId(levelPath);
    levels.push(`(${q(levelId)}, ${level.number}, ${q(level.title)}, ${q(level.subtitle)})`);
    level.tracks.forEach((track, ti) => {
      const trackPath = `${levelPath}/${track.key}`;
      const trackId = stableId(trackPath);
      tracks.push(
        `(${q(trackId)}, ${q(levelId)}, ${q(track.title)}, ${q(track.description)}, ${q(track.accent ?? 'green')}, ${q(track.introAudioUrl)}, ${ti})`,
      );
      track.sections.forEach((section, si) => walkSection(section, trackId, trackPath, null, null, si));
    });
  }

  const block = (table, cols, rows) =>
    rows.length ? `insert into public.${table} (${cols}) values\n  ${rows.join(',\n  ')};\n` : '';

  const sql = [
    '-- Generated by scripts/build-seed.mjs from legacy/src/data. Do not edit by hand.\n',
    block('levels', 'id, number, title, subtitle', levels),
    block('tracks', 'id, level_id, title, description, accent, intro_audio_url, sort', tracks),
    block('sections', 'id, track_id, parent_id, title, description, intro_audio_url, sort', sections),
    block('items', 'id, section_id, kind, title, full_title, description, url, sort', items),
  ].join('\n');

  const duplicateUrls = [...byUrl.entries()]
    .filter(([, titles]) => titles.length > 1)
    .map(([url, titles]) => ({ url, titles }));

  return { sql, report: { items: items.length, duplicateUrls } };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { contentMap } = await import('./content-map.mjs');
  const { sql, report } = buildSeed(contentMap);
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'seed.sql');
  writeFileSync(out, sql);
  console.log(`items: ${report.items}`);
  for (const d of report.duplicateUrls) console.log(`duplicate url: ${d.url} → ${d.titles.join(' | ')}`);
}
